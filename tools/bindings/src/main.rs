fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = env::args().skip(1).any(|arg| arg == "--check");
    let root = env::current_dir()?;
    let cache = env::temp_dir().join(format!("winio-winui-bindings-{WINDOWS_APP_SDK_VERSION}"));
    fs::create_dir_all(&cache)?;

    let packages = acquire_packages(&cache)?;
    let (rust, provenance, references, types) = generate(&root, &cache, &packages)?;
    let expected = [
        (root.join(BINDINGS_DIR).join(OUTPUT_NAME), rust),
        (root.join(BINDINGS_DIR).join(LOCK_NAME), provenance),
        (root.join(BINDINGS_DIR).join(REFERENCES_NAME), references),
        (root.join(BINDINGS_DIR).join(TYPES_NAME), types),
    ];

    if check {
        let mut mismatch = false;
        for (path, generated) in expected {
            let committed = fs::read_to_string(&path).unwrap_or_default();
            if committed != generated {
                eprintln!("generated file differs: {}", path.display());
                mismatch = true;
            }
        }
        if mismatch {
            return Err("bindings are stale; run `mise run bindings`".into());
        }
        println!("bindings and provenance match the pinned metadata");
    } else {
        fs::create_dir_all(root.join(BINDINGS_DIR))?;
        for (path, generated) in expected {
            fs::write(path, generated)?;
        }
        println!(
            "generated broad supplemental projection from Windows App SDK {WINDOWS_APP_SDK_VERSION}"
        );
    }
    Ok(())
}

fn acquire_packages(cache: &Path) -> Result<Vec<Package>, Box<dyn std::error::Error>> {
    let umbrella = fetch_package(cache, "Microsoft.WindowsAppSDK", WINDOWS_APP_SDK_VERSION)?;
    let nuspec = read_nuspec(&umbrella.path)?;
    let document = roxmltree::Document::parse(&nuspec)?;
    let mut packages = vec![umbrella];
    for id in COMPONENTS {
        let version = document
            .descendants()
            .find(|node| node.has_tag_name("dependency") && node.attribute("id") == Some(id))
            .and_then(|node| node.attribute("version"))
            .ok_or_else(|| format!("umbrella nuspec does not pin component {id}"))?
            .trim_matches(['[', ']'])
            .to_string();
        packages.push(fetch_package(cache, id, &version)?);
    }
    // WebView2 is outside the umbrella's direct dependency list. Its exact
    // version is declared by the selected WinUI package nuspec.
    let winui = packages
        .iter()
        .find(|package| package.id == "Microsoft.WindowsAppSDK.WinUI")
        .ok_or("WinUI package missing from UI closure")?;
    let winui_nuspec_text = read_nuspec(&winui.path)?;
    let winui_nuspec = roxmltree::Document::parse(&winui_nuspec_text)?;
    let webview2_version = winui_nuspec
        .descendants()
        .find(|node| {
            node.has_tag_name("dependency")
                && node.attribute("id") == Some("Microsoft.Web.WebView2")
        })
        .and_then(|node| node.attribute("version"))
        .ok_or("WinUI nuspec does not declare Microsoft.Web.WebView2")?
        .trim_matches(['[', ']'])
        .to_string();
    packages.push(fetch_package(
        cache,
        "Microsoft.Web.WebView2",
        &webview2_version,
    )?);
    Ok(packages)
}

fn fetch_package(
    cache: &Path,
    id: &str,
    version: &str,
) -> Result<Package, Box<dyn std::error::Error>> {
    let file_name = format!("{id}.{version}.nupkg");
    let path = cache.join(&file_name);
    if !path.is_file() {
        let url = format!(
            "https://api.nuget.org/v3-flatcontainer/{}/{}/{}",
            id.to_ascii_lowercase(),
            version.to_ascii_lowercase(),
            file_name.to_ascii_lowercase()
        );
        let mut response = ureq::get(&url).call()?;
        let mut bytes = Vec::new();
        response.body_mut().as_reader().read_to_end(&mut bytes)?;
        let mut file = fs::File::create(&path)?;
        file.write_all(&bytes)?;
        file.sync_all()?;
    }
    let sha256 = hash_file(&path)?;
    Ok(Package {
        id: id.to_string(),
        version: version.to_string(),
        path,
        sha256,
    })
}

fn read_nuspec(package: &Path) -> Result<String, Box<dyn std::error::Error>> {
    let file = fs::File::open(package)?;
    let mut archive = ZipArchive::new(file)?;
    for index in 0..archive.len() {
        let mut entry = archive.by_index(index)?;
        if entry.name().ends_with(".nuspec") {
            let mut value = String::new();
            entry.read_to_string(&mut value)?;
            return Ok(value);
        }
    }
    Err(format!("no nuspec in {}", package.display()).into())
}

fn materialize_winmd(
    packages: &[Package],
    cache: &Path,
) -> Result<Vec<WinmdInput>, Box<dyn std::error::Error>> {
    let metadata_dir = cache.join("metadata");
    if metadata_dir.exists() {
        fs::remove_dir_all(&metadata_dir)?;
    }
    fs::create_dir_all(&metadata_dir)?;

    let mut inputs = Vec::new();
    for package in packages.iter().filter(|package| {
        COMPONENTS.contains(&package.id.as_str()) || package.id == "Microsoft.Web.WebView2"
    }) {
        if package.id == "Microsoft.WindowsAppSDK.Base" {
            // Base is part of the provenance closure, but is expected to have
            // no WinMD. Verify this against the archived package each run.
            let file = fs::File::open(&package.path)?;
            let mut archive = ZipArchive::new(file)?;
            if (0..archive.len()).any(|index| {
                archive
                    .by_index(index)
                    .ok()
                    .is_some_and(|entry| entry.name().to_ascii_lowercase().ends_with(".winmd"))
            }) {
                return Err(
                    "Microsoft.WindowsAppSDK.Base unexpectedly contains WinMD metadata".into(),
                );
            }
            continue;
        }
        let file = fs::File::open(&package.path)?;
        let mut archive = ZipArchive::new(file)?;
        let names: Vec<String> = (0..archive.len())
            .filter_map(|index| {
                archive
                    .by_index(index)
                    .ok()
                    .map(|entry| entry.name().replace('\\', "/"))
            })
            .filter(|name| name.to_ascii_lowercase().ends_with(".winmd"))
            .collect();

        let selected: HashSet<String> =
            if package.id == "Microsoft.WindowsAppSDK.InteractiveExperiences" {
                let newest = names
                    .iter()
                    .filter_map(|name| {
                        let rest = name.strip_prefix("metadata/")?;
                        let (dir, file) = rest.split_once('/')?;
                        if file.contains('/') {
                            return None;
                        }
                        Some(dir.to_string())
                    })
                    .max_by(|left, right| compare_version_dirs(left, right))
                    .ok_or("InteractiveExperiences contains no versioned WinMD metadata")?;
                names
                    .iter()
                    .filter(|name| {
                        name.strip_prefix(&format!("metadata/{newest}/"))
                            .is_some_and(|rest| !rest.contains('/'))
                    })
                    .cloned()
                    .collect()
            } else if package.id == "Microsoft.Web.WebView2" {
                names
                    .iter()
                    .filter(|name| *name == "lib/Microsoft.Web.WebView2.Core.winmd")
                    .cloned()
                    .collect()
            } else {
                names
                    .iter()
                    .filter(|name| {
                        name.strip_prefix("metadata/")
                            .is_some_and(|rest| !rest.contains('/'))
                    })
                    .cloned()
                    .collect()
            };

        if selected.is_empty() {
            return Err(format!(
                "{} {} contains no selected WinMD metadata",
                package.id, package.version
            )
            .into());
        }

        for index in 0..archive.len() {
            let mut entry = archive.by_index(index)?;
            let source_path = entry.name().replace('\\', "/");
            if !selected.contains(&source_path) {
                continue;
            }
            let mut data = Vec::new();
            entry.read_to_end(&mut data)?;
            let output_name = format!(
                "{}-{}-{}",
                package.id,
                package.version,
                source_path.replace('/', "__")
            );
            let output = metadata_dir.join(output_name);
            fs::write(&output, &data)?;
            inputs.push(WinmdInput {
                package_id: package.id.clone(),
                package_version: package.version.clone(),
                source_path,
                path: output,
                sha256: hex(&Sha256::digest(data)),
            });
        }
    }
    inputs.sort_by(|left, right| {
        (&left.package_id, &left.source_path).cmp(&(&right.package_id, &right.source_path))
    });
    Ok(inputs)
}

fn compare_version_dirs(left: &str, right: &str) -> std::cmp::Ordering {
    let parse = |value: &str| {
        value
            .split('.')
            .map(|part| part.parse::<u64>().unwrap_or(0))
            .collect::<Vec<_>>()
    };
    parse(left).cmp(&parse(right))
}
fn generate(
    root: &Path,
    cache: &Path,
    packages: &[Package],
) -> Result<(String, String, String, String), Box<dyn std::error::Error>> {
    let upstream = resolved_upstream_source(root)?;
    let upstream_types = inventory_upstream(&upstream)?;
    let metadata = materialize_winmd(packages, cache)?;
    let out_dir = cache.join("bindgen-output");
    fs::create_dir_all(&out_dir)?;

    let probe_path = out_dir.join("metadata-surface.rs");
    let (probe_warnings, _) = run_bindgen(
        &metadata,
        &probe_path,
        BindgenPass::MetadataSurface,
        &BTreeSet::new(),
        &BTreeSet::new(),
    )?;
    let mut metadata_types = inventory_generated(&probe_path)?;
    retain_filter_scope(&mut metadata_types);
    eprintln!(
        "metadata-surface probe: {} types, {} diagnostic warnings",
        metadata_types.len(),
        probe_warnings.len()
    );

    let projection_references: BTreeSet<_> = metadata_types
        .intersection(&upstream_types)
        .cloned()
        .collect();
    let mut references = projection_references.clone();
    let mut dependency_filters = BTreeSet::new();
    extend_dependency_closure(
        &probe_warnings,
        &upstream_types,
        &mut references,
        &mut dependency_filters,
    );
    eprintln!(
        "probe seeded closure with {} upstream references and {} supplemental dependency filters",
        references.len(),
        dependency_filters.len()
    );
    let output_path = out_dir.join("bindings.rs");
    let mut warnings = Vec::new();
    for round in 0..MAX_CLOSURE_ROUNDS {
        eprintln!(
            "dependency closure round {}: {} upstream references, {} supplemental dependency filters",
            round + 1,
            references.len(),
            dependency_filters.len()
        );
        (warnings, _) = run_bindgen(
            &metadata,
            &output_path,
            BindgenPass::FinalProjection,
            &references,
            &dependency_filters,
        )?;
        eprintln!(
            "dependency closure round {} produced {} warning(s)",
            round + 1,
            warnings.len()
        );
        let emitted_types = inventory_generated(&output_path)?;
        let promoted_references =
            extend_emitted_upstream_references(&emitted_types, &upstream_types, &mut references);
        let diagnostics_changed = extend_dependency_closure(
            &warnings,
            &upstream_types,
            &mut references,
            &mut dependency_filters,
        );
        if promoted_references != 0 {
            eprintln!(
                "dependency closure round {} promoted {} emitted upstream type(s) to exact references",
                round + 1,
                promoted_references
            );
        }
        if warnings.is_empty() && promoted_references == 0 {
            eprintln!(
                "dependency closure converged after {} round(s): {} upstream references, {} supplemental dependency filters",
                round + 1,
                references.len(),
                dependency_filters.len()
            );
            break;
        }
        if promoted_references == 0 && !diagnostics_changed {
            return Err(format!(
                "dependency closure stalled with {} bindgen warning(s):\n{}",
                warnings.len(),
                warnings
                    .iter()
                    .take(20)
                    .cloned()
                    .collect::<Vec<_>>()
                    .join("\n")
            )
            .into());
        }
        if round + 1 == MAX_CLOSURE_ROUNDS {
            return Err(format!(
                "dependency closure did not converge after {MAX_CLOSURE_ROUNDS} rounds; {} warning(s) remain",
                warnings.len()
            )
            .into());
        }
    }

    let raw_source = fs::read_to_string(&output_path)?;
    let raw_generated_types = inventory_generated(&output_path)?;
    let (source, sanitize_stats) =
        sanitize_projection(&raw_source, &references, &raw_generated_types)?;
    fs::write(&output_path, &source)?;
    let generated_types = inventory_generated_reader(source.as_bytes())?;
    if generated_types != raw_generated_types {
        return Err("projection sanitizer changed the generated type inventory".into());
    }
    validate_standard_windows_surface(&generated_types)?;
    let mut generated_root_types = generated_types.clone();
    retain_filter_scope(&mut generated_root_types);
    validate_partition(
        &metadata_types,
        &projection_references,
        &generated_root_types,
    )?;
    validate_no_overlap(&references, &generated_types)?;
    if !warnings.is_empty() {
        return Err(format!(
            "final broad bindgen pass emitted {} warning(s) after closure",
            warnings.len()
        )
        .into());
    }
    validate_wrapper_contracts(&source)?;

    let generated = format!("{HEADER}{source}");
    let references_text = manifest_text(&references);
    let types_text = manifest_text(&generated_types);
    let mut provenance = String::from("# Generated by tools/bindings; do not edit.\n\n");
    provenance.push_str(&format!(
        "windows_app_sdk_version = \"{WINDOWS_APP_SDK_VERSION}\"\ngenerator_package = \"{BINDGEN_PACKAGE}\"\ngenerator_version = \"{BINDGEN_VERSION}\"\nwebview2_version_source = \"Microsoft.WindowsAppSDK.WinUI {winui_version} nuspec dependency\"\nbase_winmd_policy = \"package recorded; no WinMD present\"\n\n[projection]\nupstream_package = \"winio-winui3\"\nupstream_version = \"{UPSTREAM_VERSION}\"\nupstream_vcs_commit = \"{UPSTREAM_SHA}\"\nfilter_scope = [\"Microsoft.UI.Xaml\", \"Windows.UI.Xaml.Interop\"]\nmetadata_type_count = {metadata_count}\nupstream_reference_count = {reference_count}\nsupplemental_type_count = {generated_count}\ndependency_filter_count = {dependency_filter_count}\nstripped_upstream_forwarding_methods = {stripped_forwarders}\nstripped_iterator_impls = {stripped_iterators}\nstripped_unresolved_hierarchy_entries = {stripped_hierarchy}\nreferences_sha256 = \"{references_hash}\"\ntypes_sha256 = \"{types_hash}\"\nfinal_warning_count = {warning_count}\n\n",
        winui_version = packages.iter().find(|package| package.id == "Microsoft.WindowsAppSDK.WinUI").map(|package| package.version.as_str()).unwrap_or("missing"),
        metadata_count = metadata_types.len(),
        reference_count = references.len(),
        generated_count = generated_types.len(),
        dependency_filter_count = dependency_filters.len(),
        stripped_forwarders = sanitize_stats.stripped_upstream_forwarding_methods,
        stripped_iterators = sanitize_stats.stripped_iterator_impls,
        stripped_hierarchy = sanitize_stats.stripped_unresolved_hierarchy_entries,
        references_hash = sha256_text(&references_text),
        types_hash = sha256_text(&types_text),
        warning_count = warnings.len()
    ));
    for package in packages {
        provenance.push_str("[[package]]\n");
        provenance.push_str(&format!(
            "id = \"{}\"\nversion = \"{}\"\nsha256 = \"{}\"\n",
            package.id, package.version, package.sha256
        ));
    }
    for input in &metadata {
        provenance.push_str("[[winmd_input]]\n");
        provenance.push_str(&format!("package_id = \"{}\"\npackage_version = \"{}\"\nsource_path = \"{}\"\nsha256 = \"{}\"\n\n", input.package_id, input.package_version, input.source_path, input.sha256));
    }
    Ok((generated, provenance, references_text, types_text))
}

fn run_bindgen(
    metadata: &[WinmdInput],
    output: &Path,
    pass: BindgenPass,
    upstream_references: &BTreeSet<String>,
    dependency_filters: &BTreeSet<String>,
) -> Result<(Vec<String>, ()), Box<dyn std::error::Error>> {
    let mut args = vec!["--in".to_string(), "default".to_string()];
    args.extend(
        metadata
            .iter()
            .map(|input| input.path.to_string_lossy().into_owned()),
    );
    args.extend([
        "--out".into(),
        output.to_string_lossy().into_owned(),
        "--overrides".into(),
        "--no-deps".into(),
    ]);
    for filter in ROOT_FILTERS {
        args.extend(["--filter".into(), (*filter).into()]);
    }
    for filter in dependency_filters {
        args.extend(["--filter".into(), filter.clone()]);
    }
    // Pass A has no broad Windows reference so Interop remains visible in M.
    // Pass B excludes every upstream projection before applying references.
    if let BindgenPass::FinalProjection = pass {
        for name in upstream_references {
            args.extend(["--reference".into(), format!("winio_winui3,full,{name}")]);
        }
        // Bindgen references satisfy dependencies but do not suppress types
        // selected directly by the broad namespace filters. Exclude the exact
        // referenced names from local generation to enforce R intersect G = 0.
        for name in upstream_references {
            args.extend(["--filter".into(), format!("!{name}")]);
        }
    }
    for reference in [
        "windows_collections,flat,Windows.Foundation.Collections.IIterable",
        "windows_collections,flat,Windows.Foundation.Collections.IIterator",
        "windows_collections,flat,Windows.Foundation.Collections.IKeyValuePair",
        "windows_collections,flat,Windows.Foundation.Collections.IMap",
        "windows_collections,flat,Windows.Foundation.Collections.IMapView",
        "windows_collections,flat,Windows.Foundation.Collections.IVector",
        "windows_collections,flat,Windows.Foundation.Collections.IVectorView",
        "windows_numerics,flat,Windows.Foundation.Numerics.Matrix3x2",
        "windows_numerics,flat,Windows.Foundation.Numerics.Matrix4x4",
        "windows_numerics,flat,Windows.Foundation.Numerics.Vector2",
        "windows_numerics,flat,Windows.Foundation.Numerics.Vector3",
        "windows_numerics,flat,Windows.Foundation.Numerics.Vector4",
        "windows_future,flat,Windows.Foundation.Async*",
        "windows_future,flat,Windows.Foundation.IAsync*",
    ] {
        args.extend(["--reference".into(), reference.into()]);
    }
    if let BindgenPass::FinalProjection = pass {
        // Keep broad Windows last: exact WinUI Interop references must win.
        args.extend(["--reference".into(), "windows,skip-root,Windows".into()]);
    }
    let mut warnings: Vec<_> = overrides_windows_bindgen::bindgen(&args)
        .iter()
        .cloned()
        .collect();
    warnings.sort();
    warnings.dedup();
    Ok((warnings, ()))
}

fn extend_dependency_closure(
    warnings: &[String],
    upstream_types: &BTreeSet<String>,
    references: &mut BTreeSet<String>,
    dependency_filters: &mut BTreeSet<String>,
) -> bool {
    let mut changed = false;
    for name in missing_dependency_names(warnings) {
        if name.starts_with("Windows.") && !name.starts_with("Windows.UI.Xaml.Interop.") {
            continue;
        }
        if upstream_types.contains(&name) {
            changed |= references.insert(name);
        } else {
            changed |= dependency_filters.insert(name);
        }
    }
    changed
}

fn extend_emitted_upstream_references(
    emitted_types: &BTreeSet<String>,
    upstream_types: &BTreeSet<String>,
    references: &mut BTreeSet<String>,
) -> usize {
    emitted_types
        .intersection(upstream_types)
        .filter(|name| name.starts_with("Microsoft."))
        .filter(|name| references.insert((*name).clone()))
        .count()
}

fn missing_dependency_names(warnings: &[String]) -> BTreeSet<String> {
    warnings
        .iter()
        .flat_map(|warning| warning.lines())
        .map(str::trim)
        .filter(|line| line.starts_with("Microsoft.") || line.starts_with("Windows."))
        .filter(|line| {
            line.chars()
                .all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '.')
        })
        .map(str::to_string)
        .collect()
}

fn resolved_upstream_source(root: &Path) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let cargo = env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let output = Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--locked"])
        .current_dir(root)
        .output()?;
    if !output.status.success() {
        return Err(format!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&output.stderr)
        )
        .into());
    }
    let value: serde_json::Value = serde_json::from_slice(&output.stdout)?;
    let packages = value["packages"]
        .as_array()
        .ok_or("cargo metadata omitted packages")?;
    let matches: Vec<_> = packages
        .iter()
        .filter(|p| p["name"] == "winio-winui3" && p["version"] == UPSTREAM_VERSION)
        .collect();
    if matches.len() != 1 {
        return Err(format!(
            "expected exactly one resolved winio-winui3 {UPSTREAM_VERSION}, found {}",
            matches.len()
        )
        .into());
    }
    let manifest = PathBuf::from(
        matches[0]["manifest_path"]
            .as_str()
            .ok_or("upstream manifest path missing")?,
    );
    let package_manifest = manifest
        .parent()
        .ok_or("upstream manifest has no parent")?
        .join("Cargo.toml.orig");
    let original = fs::read_to_string(package_manifest)?;
    if !original.contains("name = \"winio-winui3\"") || !original.contains("version = \"0.4.4\"") {
        return Err("upstream Cargo.toml.orig package identity mismatch".into());
    }
    let package_root = manifest.parent().unwrap();
    let vcs = package_root.join(".cargo_vcs_info.json");
    if vcs.is_file() {
        let value: serde_json::Value = serde_json::from_slice(&fs::read(vcs)?)?;
        if value["git"]["sha1"] != UPSTREAM_SHA {
            return Err("upstream VCS commit mismatch".into());
        }
    }
    Ok(package_root.join("src"))
}

fn inventory_upstream(source: &Path) -> Result<BTreeSet<String>, Box<dyn std::error::Error>> {
    let mut files = Vec::new();
    for namespace in ["Microsoft", "Windows/UI/Xaml/Interop"] {
        collect_mod_files(&source.join(namespace), &mut files)?;
    }
    inventory_files(source, &files)
}

fn collect_mod_files(
    path: &Path,
    files: &mut Vec<PathBuf>,
) -> Result<(), Box<dyn std::error::Error>> {
    if !path.exists() {
        return Ok(());
    }
    for entry in fs::read_dir(path)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            collect_mod_files(&path, files)?;
        } else if path.file_name().is_some_and(|name| name == "mod.rs") {
            files.push(path);
        }
    }
    Ok(())
}

fn inventory_files(
    root: &Path,
    files: &[PathBuf],
) -> Result<BTreeSet<String>, Box<dyn std::error::Error>> {
    let mut names = BTreeSet::new();
    for file in files {
        let relative = file.strip_prefix(root)?;
        let namespace = relative.parent().unwrap_or(Path::new(""));
        let prefix = namespace
            .components()
            .map(|part| part.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join(".");
        inventory_upstream_reader(BufReader::new(fs::File::open(file)?), &prefix, &mut names)?;
    }
    Ok(names)
}

fn inventory_upstream_reader<R: BufRead>(
    reader: R,
    namespace: &str,
    names: &mut BTreeSet<String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut awaiting_interface = false;
    for line in reader.lines() {
        let line = line?;
        let trimmed = line.trim();

        if awaiting_interface {
            if let Some(name) = first_identifier(trimmed) {
                add_metadata_name(names, namespace, name.to_string());
            }
            awaiting_interface = false;
            continue;
        }

        if let Some(arguments) = interface_macro_arguments(trimmed) {
            if let Some(name) = first_identifier(arguments) {
                add_metadata_name(names, namespace, name.to_string());
            } else {
                awaiting_interface = true;
            }
            continue;
        }

        for keyword in ["pub struct ", "pub enum ", "pub type "] {
            if let Some(rest) = trimmed.strip_prefix(keyword) {
                if let Some(name) = first_identifier(rest) {
                    add_metadata_name(names, namespace, name.to_string());
                }
                break;
            }
        }
    }
    Ok(())
}

fn inventory_generated(path: &Path) -> Result<BTreeSet<String>, Box<dyn std::error::Error>> {
    inventory_generated_reader(BufReader::new(fs::File::open(path)?))
}

fn retain_filter_scope(names: &mut BTreeSet<String>) {
    names.retain(|name| {
        name.starts_with("Microsoft.UI.Xaml.") || name.starts_with("Windows.UI.Xaml.Interop.")
    });
}

fn validate_standard_windows_surface(
    names: &BTreeSet<String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let locally_generated_standard: Vec<_> = names
        .iter()
        .filter(|name| {
            name.starts_with("Windows.") && !name.starts_with("Windows.UI.Xaml.Interop.")
        })
        .take(20)
        .cloned()
        .collect();
    if !locally_generated_standard.is_empty() {
        return Err(format!(
            "final projection locally defines standard Windows metadata types: {locally_generated_standard:?}"
        )
        .into());
    }
    Ok(())
}

#[derive(Clone, Copy)]
enum GeneratedToken<'a> {
    Ident(&'a str),
    LBrace,
    RBrace,
    LParen,
    Bang,
    Other,
}

fn inventory_generated_reader<R: Read>(
    mut reader: R,
) -> Result<BTreeSet<String>, Box<dyn std::error::Error>> {
    let mut source = String::new();
    reader.read_to_string(&mut source)?;
    let mut names = BTreeSet::new();
    let mut modules: Vec<(usize, String)> = Vec::new();
    let mut depth = 0usize;
    let mut cursor = 0usize;
    let mut declaration: Option<&'static str> = None;
    let mut pending_module: Option<String> = None;
    let mut saw_pub = false;
    let mut interface_state = 0u8;

    while let Some(token) = next_generated_token(&source, &mut cursor) {
        match token {
            GeneratedToken::LBrace => {
                depth += 1;
                if let Some(module) = pending_module.take() {
                    modules.push((depth, module));
                }
                saw_pub = false;
                declaration = None;
                interface_state = 0;
            }
            GeneratedToken::RBrace => {
                if modules
                    .last()
                    .is_some_and(|(module_depth, _)| *module_depth == depth)
                {
                    modules.pop();
                }
                depth = depth.saturating_sub(1);
                saw_pub = false;
                declaration = None;
                pending_module = None;
                interface_state = 0;
            }
            GeneratedToken::Ident(identifier) => {
                if interface_state == 3 {
                    add_metadata_name(
                        &mut names,
                        &module_namespace(&modules),
                        identifier.to_string(),
                    );
                    interface_state = 0;
                } else if identifier == "define_interface" {
                    interface_state = 1;
                } else if interface_state != 0 {
                    interface_state = 0;
                }

                if let Some(kind) = declaration.take() {
                    if kind == "mod" {
                        pending_module = Some(identifier.to_string());
                    } else {
                        add_metadata_name(
                            &mut names,
                            &module_namespace(&modules),
                            identifier.to_string(),
                        );
                    }
                    saw_pub = false;
                    continue;
                }

                if saw_pub {
                    declaration = match identifier {
                        "mod" => Some("mod"),
                        "struct" => Some("struct"),
                        "enum" => Some("enum"),
                        "type" => Some("type"),
                        _ => None,
                    };
                    if declaration.is_none() {
                        saw_pub = identifier == "pub";
                    }
                } else {
                    saw_pub = identifier == "pub";
                }
            }
            GeneratedToken::Bang => {
                interface_state = if interface_state == 1 { 2 } else { 0 };
                saw_pub = false;
            }
            GeneratedToken::LParen => {
                interface_state = if interface_state == 2 { 3 } else { 0 };
                saw_pub = false;
            }
            GeneratedToken::Other => {
                if pending_module.is_some() {
                    pending_module = None;
                }
                if declaration.is_some() {
                    declaration = None;
                }
                saw_pub = false;
                if interface_state != 0 {
                    interface_state = 0;
                }
            }
        }
    }
    Ok(names)
}

fn next_generated_token<'a>(source: &'a str, cursor: &mut usize) -> Option<GeneratedToken<'a>> {
    let bytes = source.as_bytes();
    while *cursor < bytes.len() {
        let start = *cursor;
        let byte = bytes[start];
        if byte.is_ascii_whitespace() {
            *cursor += 1;
            continue;
        }
        if byte == b'/' && bytes.get(start + 1) == Some(&b'/') {
            *cursor += 2;
            while *cursor < bytes.len() && bytes[*cursor] != b'\n' {
                *cursor += 1;
            }
            continue;
        }
        if byte == b'/' && bytes.get(start + 1) == Some(&b'*') {
            *cursor += 2;
            let mut nesting = 1usize;
            while *cursor + 1 < bytes.len() && nesting != 0 {
                if bytes[*cursor] == b'/' && bytes[*cursor + 1] == b'*' {
                    nesting += 1;
                    *cursor += 2;
                } else if bytes[*cursor] == b'*' && bytes[*cursor + 1] == b'/' {
                    nesting -= 1;
                    *cursor += 2;
                } else {
                    *cursor += 1;
                }
            }
            continue;
        }
        if let Some(end) = char_literal_end(bytes, start) {
            *cursor = end;
            return Some(GeneratedToken::Other);
        }
        if let Some(end) = raw_string_end(bytes, start) {
            *cursor = end;
            return Some(GeneratedToken::Other);
        }
        if byte == b'"' {
            *cursor = quoted_string_end(bytes, start + 1);
            return Some(GeneratedToken::Other);
        }
        match byte {
            b'{' => {
                *cursor += 1;
                return Some(GeneratedToken::LBrace);
            }
            b'}' => {
                *cursor += 1;
                return Some(GeneratedToken::RBrace);
            }
            b'(' => {
                *cursor += 1;
                return Some(GeneratedToken::LParen);
            }
            b'!' => {
                *cursor += 1;
                return Some(GeneratedToken::Bang);
            }
            _ if byte == b'_' || byte.is_ascii_alphabetic() => {
                *cursor += 1;
                while *cursor < bytes.len()
                    && (bytes[*cursor] == b'_' || bytes[*cursor].is_ascii_alphanumeric())
                {
                    *cursor += 1;
                }
                return Some(GeneratedToken::Ident(&source[start..*cursor]));
            }
            _ => {
                *cursor += 1;
                return Some(GeneratedToken::Other);
            }
        }
    }
    None
}

fn quoted_string_end(bytes: &[u8], mut cursor: usize) -> usize {
    while cursor < bytes.len() {
        match bytes[cursor] {
            b'\\' => cursor = (cursor + 2).min(bytes.len()),
            b'"' => return cursor + 1,
            _ => cursor += 1,
        }
    }
    cursor
}

fn char_literal_end(bytes: &[u8], start: usize) -> Option<usize> {
    let mut cursor = start;
    if bytes.get(cursor) == Some(&b'b') {
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'\'') {
        return None;
    }
    cursor += 1;
    match bytes.get(cursor)? {
        b'\\' => {
            cursor += 1;
            match bytes.get(cursor)? {
                b'u' if bytes.get(cursor + 1) == Some(&b'{') => {
                    cursor += 2;
                    while let Some(byte) = bytes.get(cursor) {
                        cursor += 1;
                        if *byte == b'}' {
                            break;
                        }
                    }
                }
                _ => cursor += 1,
            }
        }
        byte if *byte == b'\'' || *byte == b'\n' || *byte == b'\r' => return None,
        byte if byte.is_ascii() => cursor += 1,
        _ => {
            let tail = std::str::from_utf8(&bytes[cursor..]).ok()?;
            let ch = tail.chars().next()?;
            cursor += ch.len_utf8();
        }
    }
    (bytes.get(cursor) == Some(&b'\'')).then_some(cursor + 1)
}

fn raw_string_end(bytes: &[u8], start: usize) -> Option<usize> {
    let mut cursor = start;
    if bytes.get(cursor) == Some(&b'b') {
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'r') {
        return None;
    }
    cursor += 1;
    let hashes_start = cursor;
    while bytes.get(cursor) == Some(&b'#') {
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'"') {
        return None;
    }
    let hash_count = cursor - hashes_start;
    cursor += 1;
    while cursor < bytes.len() {
        if bytes[cursor] == b'"'
            && bytes.get(cursor + 1..cursor + 1 + hash_count)
                == Some(&bytes[hashes_start..hashes_start + hash_count])
        {
            return Some(cursor + 1 + hash_count);
        }
        cursor += 1;
    }
    Some(bytes.len())
}

fn interface_macro_arguments(line: &str) -> Option<&str> {
    let bang = line.find('!')?;
    let macro_path = line[..bang].trim();
    if macro_path.rsplit("::").next()? != "define_interface" {
        return None;
    }
    line[bang + 1..].trim_start().strip_prefix('(')
}

fn module_namespace(modules: &[(usize, String)]) -> String {
    modules
        .iter()
        .map(|(_, module)| module.as_str())
        .collect::<Vec<_>>()
        .join(".")
}

fn first_identifier(value: &str) -> Option<&str> {
    let token = value
        .trim_start()
        .split(|ch: char| !(ch == '_' || ch.is_ascii_alphanumeric()))
        .next()?;
    (!token.is_empty()).then_some(token)
}

fn add_metadata_name(names: &mut BTreeSet<String>, namespace: &str, name: String) {
    if name.ends_with("_Vtbl") || name.ends_with("_Impl") {
        return;
    }
    names.insert(if namespace.is_empty() {
        name
    } else {
        format!("{namespace}.{name}")
    });
}

fn sanitize_projection(
    source: &str,
    references: &BTreeSet<String>,
    generated_types: &BTreeSet<String>,
) -> Result<(String, SanitizeStats), Box<dyn std::error::Error>> {
    let (source, stripped_upstream_forwarding_methods) = strip_upstream_forwarding_methods(source)?;
    let (source, stripped_iterator_impls) = strip_broken_iterator_impls(&source)?;
    let (source, stripped_unresolved_hierarchy_entries) =
        strip_unresolved_hierarchy_entries(&source, references, generated_types)?;
    Ok((
        source,
        SanitizeStats {
            stripped_upstream_forwarding_methods,
            stripped_iterator_impls,
            stripped_unresolved_hierarchy_entries,
        },
    ))
}

fn strip_upstream_forwarding_methods(
    source: &str,
) -> Result<(String, usize), Box<dyn std::error::Error>> {
    let mut spans = Vec::new();
    let mut cursor = 0;
    while let Some(relative) = source[cursor..].find("pub fn ") {
        let start = cursor + relative;
        if start > 0 {
            let before = source.as_bytes()[start - 1];
            if before != b' ' && before != b'\t' && before != b'\n' && before != b'\r' {
                cursor = start + 7;
                continue;
            }
        }
        let Some(open_relative) = source[start..].find('{') else {
            break;
        };
        let open = start + open_relative;
        if source[start..open].contains(';') {
            cursor = open + 1;
            continue;
        }
        let end = matching_delimiter(source, open, b'{', b'}')? + 1;
        let method = &source[start..end];
        if method.contains("windows_core::Interface::cast")
            && method.contains("winio_winui3::")
            && method.contains("windows_core::Interface::vtable")
        {
            spans.push((
                preceding_attribute_start(source, start),
                include_trailing_newline(source, end),
            ));
        }
        cursor = end;
    }
    Ok((remove_spans(source, &spans)?, spans.len()))
}

fn strip_broken_iterator_impls(
    source: &str,
) -> Result<(String, usize), Box<dyn std::error::Error>> {
    let mut candidates = Vec::new();
    let mut cursor = 0;
    const PREFIX: &str = "impl IntoIterator for ";
    while let Some(relative) = source[cursor..].find(PREFIX) {
        let start = cursor + relative;
        let header_start = start + PREFIX.len();
        let Some(open_relative) = source[header_start..].find('{') else {
            break;
        };
        let open = header_start + open_relative;
        let target = source[header_start..open].trim();
        let type_name = target.trim_start_matches('&').trim();
        let end = matching_delimiter(source, open, b'{', b'}')? + 1;
        let body = &source[open..end];
        if body.contains("self.First().unwrap()") || body.contains("IntoIterator::into_iter(&self)")
        {
            candidates.push((
                preceding_attribute_start(source, start),
                include_trailing_newline(source, end),
                type_name.to_string(),
            ));
        }
        cursor = end;
    }

    let broken: BTreeSet<_> = candidates
        .iter()
        .filter(|(_, _, type_name)| !type_has_method(source, type_name, "First"))
        .map(|(_, _, type_name)| type_name.clone())
        .collect();
    let spans: Vec<_> = candidates
        .into_iter()
        .filter(|(_, _, type_name)| broken.contains(type_name))
        .map(|(start, end, _)| (start, end))
        .collect();
    Ok((remove_spans(source, &spans)?, spans.len()))
}

fn type_has_method(source: &str, type_name: &str, method: &str) -> bool {
    let marker = format!("impl {type_name} {{");
    let method_marker = format!("pub fn {method}(");
    let mut cursor = 0;
    while let Some(relative) = source[cursor..].find(&marker) {
        let start = cursor + relative;
        let open = start + marker.len() - 1;
        if let Ok(end) = matching_delimiter(source, open, b'{', b'}') {
            if source[open + 1..end].contains(&method_marker) {
                return true;
            }
            cursor = end + 1;
        } else {
            return false;
        }
    }
    false
}

fn strip_unresolved_hierarchy_entries(
    source: &str,
    references: &BTreeSet<String>,
    generated_types: &BTreeSet<String>,
) -> Result<(String, usize), Box<dyn std::error::Error>> {
    let available: BTreeSet<_> = references
        .iter()
        .chain(generated_types.iter())
        .filter_map(|name| name.rsplit('.').next())
        .map(str::to_string)
        .collect();
    const PREFIX: &str = "windows_core::imp::required_hierarchy!(";
    let mut replacements = Vec::new();
    let mut cursor = 0;
    let mut removed = 0;
    while let Some(relative) = source[cursor..].find(PREFIX) {
        let start = cursor + relative;
        let open = start + PREFIX.len() - 1;
        let close = matching_delimiter(source, open, b'(', b')')?;
        let inner = &source[open + 1..close];
        let args: Vec<_> = inner
            .split(',')
            .map(str::trim)
            .filter(|arg| !arg.is_empty())
            .collect();
        if !args.is_empty() {
            let mut kept = Vec::with_capacity(args.len());
            kept.push(args[0]);
            for arg in args.iter().skip(1) {
                let is_simple = arg
                    .chars()
                    .all(|ch| ch.is_ascii_alphanumeric() || ch == '_');
                if !is_simple || available.contains(*arg) {
                    kept.push(arg);
                } else {
                    removed += 1;
                }
            }
            if kept.len() != args.len() || args.len() == 1 {
                let indent_start = source[..start].rfind('\n').map_or(0, |index| index + 1);
                let indent = &source[indent_start..start];
                let child_indent = format!("{indent}    ");
                let replacement = if kept.len() == 1 {
                    String::new()
                } else {
                    format!(
                        "{PREFIX}\n{child_indent}{}\n{indent})",
                        kept.join(&format!(",\n{child_indent}"))
                    )
                };
                let mut end = close + 1;
                if kept.len() == 1 && source.as_bytes().get(end) == Some(&b';') {
                    end += 1;
                    end = include_trailing_newline(source, end);
                }
                replacements.push((start, end, replacement));
            }
        }
        cursor = close + 1;
    }
    Ok((replace_spans(source, &replacements)?, removed))
}

fn matching_delimiter(
    source: &str,
    open: usize,
    open_byte: u8,
    close_byte: u8,
) -> Result<usize, Box<dyn std::error::Error>> {
    let bytes = source.as_bytes();
    if bytes.get(open) != Some(&open_byte) {
        return Err(format!("expected delimiter at byte {open}").into());
    }
    let mut depth = 0usize;
    for (offset, byte) in bytes[open..].iter().enumerate() {
        if *byte == open_byte {
            depth += 1;
        } else if *byte == close_byte {
            depth -= 1;
            if depth == 0 {
                return Ok(open + offset);
            }
        }
    }
    Err("unmatched generated-source delimiter".into())
}

fn preceding_attribute_start(source: &str, start: usize) -> usize {
    let line_start = source[..start].rfind('\n').map_or(0, |index| index + 1);
    if !source[line_start..start].trim().is_empty() {
        return start;
    }
    let mut current = line_start;
    while current > 0 {
        let previous_end = current.saturating_sub(1);
        let previous_start = source[..previous_end]
            .rfind('\n')
            .map_or(0, |index| index + 1);
        let previous = source[previous_start..previous_end].trim();
        if previous.starts_with("#[") {
            current = previous_start;
        } else {
            break;
        }
    }
    current
}

fn include_trailing_newline(source: &str, end: usize) -> usize {
    if source.as_bytes().get(end) == Some(&b'\n') {
        end + 1
    } else {
        end
    }
}

fn remove_spans(
    source: &str,
    spans: &[(usize, usize)],
) -> Result<String, Box<dyn std::error::Error>> {
    let replacements: Vec<_> = spans
        .iter()
        .map(|(start, end)| (*start, *end, String::new()))
        .collect();
    replace_spans(source, &replacements)
}

fn replace_spans(
    source: &str,
    replacements: &[(usize, usize, String)],
) -> Result<String, Box<dyn std::error::Error>> {
    let mut ordered = replacements.to_vec();
    ordered.sort_by_key(|(start, _, _)| *start);
    let mut out = String::with_capacity(source.len());
    let mut cursor = 0usize;
    for (start, end, replacement) in ordered {
        if start < cursor || end < start || end > source.len() {
            return Err(format!(
                "overlapping or invalid generated-source rewrite span: {start}..{end} after {cursor}, source length {}",
                source.len()
            )
            .into());
        }
        out.push_str(&source[cursor..start]);
        out.push_str(&replacement);
        cursor = end;
    }
    out.push_str(&source[cursor..]);
    Ok(out)
}

fn validate_partition(
    metadata: &BTreeSet<String>,
    references: &BTreeSet<String>,
    generated: &BTreeSet<String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let duplicate: Vec<_> = references.intersection(generated).cloned().collect();
    let covered: BTreeSet<_> = references.union(generated).cloned().collect();
    let missing: Vec<_> = metadata.difference(&covered).cloned().collect();
    let unexpected: Vec<_> = generated.difference(metadata).cloned().collect();
    if !duplicate.is_empty() || !missing.is_empty() || !unexpected.is_empty() {
        return Err(format!("projection partition failed ({} duplicate, {} missing, {} unexpected)\nduplicate: {:?}\nmissing: {:?}\nunexpected: {:?}", duplicate.len(), missing.len(), unexpected.len(), &duplicate[..duplicate.len().min(20)], &missing[..missing.len().min(20)], &unexpected[..unexpected.len().min(20)]).into());
    }
    Ok(())
}

fn validate_no_overlap(
    references: &BTreeSet<String>,
    generated: &BTreeSet<String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let duplicate: Vec<_> = references.intersection(generated).cloned().collect();
    if !duplicate.is_empty() {
        return Err(format!(
            "supplemental projection duplicated {} upstream-referenced type(s): {:?}",
            duplicate.len(),
            &duplicate[..duplicate.len().min(20)]
        )
        .into());
    }
    Ok(())
}

fn validate_wrapper_contracts(source: &str) -> Result<(), Box<dyn std::error::Error>> {
    for contract in WRAPPER_CONTRACTS {
        let short = contract.runtime_type.rsplit('.').next().unwrap();
        if !source.contains(&format!("pub struct {short}")) {
            return Err(format!(
                "broad projection lacks wrapper runtime type {} ({})",
                contract.name, contract.runtime_type
            )
            .into());
        }
        for method in contract.required_methods {
            let implementation = implementation_block(source, method.type_name)?;
            if !implementation.contains(method.fragment) {
                return Err(format!(
                    "generated bindings are missing required {} method `{}` on `{}`",
                    contract.name, method.fragment, method.type_name
                )
                .into());
            }
        }
    }
    Ok(())
}

fn manifest_text(names: &BTreeSet<String>) -> String {
    names.iter().map(|name| format!("{name}\n")).collect()
}
fn sha256_text(text: &str) -> String {
    format!("{:x}", Sha256::digest(text.as_bytes()))
}

fn implementation_block<'a>(
    source: &'a str,
    type_name: &str,
) -> Result<&'a str, Box<dyn std::error::Error>> {
    let marker = format!("impl {type_name} {{");
    let start = source
        .find(&marker)
        .ok_or_else(|| format!("generated bindings have no `{marker}` block"))?;
    let body_start = start + marker.len();
    let end = source[body_start..]
        .find("\n                impl ")
        .map(|offset| body_start + offset)
        .ok_or_else(|| {
            format!("generated `{type_name}` implementation has no closing impl boundary")
        })?;
    Ok(&source[body_start..end])
}

fn hash_file(path: &Path) -> Result<String, Box<dyn std::error::Error>> {
    let mut file = fs::File::open(path)?;
    let mut hasher = Sha256::new();
    std::io::copy(&mut file, &mut hasher)?;
    Ok(format!("{:x}", hasher.finalize()))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

